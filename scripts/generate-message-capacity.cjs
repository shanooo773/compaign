// Shared public constants are the source of the SQL policy.
const fs = require('node:fs');
const source = fs.readFileSync('shared/message-capacity.ts', 'utf8');
const student = Number(/student: (\d+)/.exec(source)[1]);
const globalLimit = Number(/global: (\d+)/.exec(source)[1]);
const check = user => `SELECT CASE WHEN (SELECT count(*) FROM active_message_capacity WHERE user_id=${user})>${student} OR (SELECT count(*) FROM active_message_capacity)>${globalLimit} THEN RAISE(ABORT,'Message storage quota reached') END;`;
let sql = `-- Generated by scripts/generate-message-capacity.cjs. Existing rows are unchanged.
-- Historical approvals, receipts, cancellations and contact evidence remain intact.
DROP TRIGGER message_capacity;
CREATE VIEW active_message_capacity AS
 SELECT m.user_id,'message:' || m.id slot FROM messages m
 WHERE m.status IN ('draft','pending') OR EXISTS(SELECT 1 FROM transports t WHERE t.message_id=m.id AND t.state IN ('leased','submitting','uncertain'))
 UNION ALL
 SELECT m.user_id,'proposal:' || m.id || ':' || j.key FROM messages m,
 json_each(CASE WHEN json_valid(m.followup_proposal) THEN CASE WHEN json_type(m.followup_proposal,'$.steps')='array' THEN json_extract(m.followup_proposal,'$.steps') ELSE json_array(json(m.followup_proposal)) END ELSE '[]' END) j
 WHERE m.followup_proposal IS NOT NULL AND m.status IN ('draft','pending') AND m.parent_id IS NULL
 AND NOT EXISTS(SELECT 1 FROM message_authorizations a WHERE a.message_id=m.id)
 AND NOT EXISTS(SELECT 1 FROM automation a WHERE a.message_id=m.id)
 UNION ALL
 SELECT m.user_id,'step:' || f.child_id FROM followup_steps f JOIN messages m ON m.id=f.root_id
 WHERE f.cancel_reason IS NULL AND m.status IN ('draft','pending','sent')
 AND NOT EXISTS(SELECT 1 FROM messages child WHERE child.id=f.child_id)
 UNION ALL
 SELECT m.user_id,'legacy:' || m.id FROM automation a JOIN messages m ON m.id=a.message_id
 WHERE a.generated=0 AND a.cancel_reason IS NULL AND m.status IN ('draft','pending','sent')
 AND NOT EXISTS(SELECT 1 FROM messages child WHERE child.parent_id=m.id)
 AND NOT EXISTS(SELECT 1 FROM followup_steps f WHERE f.root_id=m.id);
CREATE TRIGGER message_capacity AFTER INSERT ON messages BEGIN ${check('NEW.user_id')} END;
CREATE TRIGGER message_capacity_update AFTER UPDATE OF status,followup_proposal ON messages
 WHEN NEW.status IN ('draft','pending') AND (NEW.status IS NOT OLD.status OR NEW.followup_proposal IS NOT OLD.followup_proposal)
 BEGIN ${check('NEW.user_id')} END;
`;
for (const [table, owner] of [['followup_steps','root_id'], ['automation','message_id']]) {
 sql += `CREATE TRIGGER ${table}_capacity AFTER INSERT ON ${table} BEGIN ${check(`(SELECT user_id FROM messages WHERE id=NEW.${owner})`)} END;\n`;
}
sql += `CREATE TRIGGER automation_capacity_update AFTER UPDATE OF generated,cancel_reason ON automation
 WHEN NEW.generated=0 AND NEW.cancel_reason IS NULL AND (OLD.generated!=0 OR OLD.cancel_reason IS NOT NULL)
 BEGIN ${check('(SELECT user_id FROM messages WHERE id=NEW.message_id)')} END;\n`;
const target='apps/api/migrations/0018_active_message_capacity.sql';
if(process.argv.includes('--check')) { if(fs.readFileSync(target,'utf8')!==sql) throw Error('Capacity migration differs from shared policy'); }
else fs.writeFileSync(target,sql);
